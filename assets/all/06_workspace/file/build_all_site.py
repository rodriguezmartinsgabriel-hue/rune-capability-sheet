"""Stage every Rune-generated artifact and rebuild the sheet with a complete gallery."""

import html
import shutil
from pathlib import Path

BASE = Path(r"C:\Users\gabri\AppData\Local\Temp\opencode")
SITE = BASE / "rune-sheet-site"
ASSETS = SITE / "assets"
REPO = Path(r"C:\Users\gabri\Tools\game-dev\rune")

for d in ["all", "src", "scripts", "reports"]:
    (ASSETS / d).mkdir(parents=True, exist_ok=True)

manifest = []


def cp(src, group, rename=None):
    src = Path(src)
    if not src.exists() or not src.is_file():
        return
    ext = src.suffix.lower()
    sub = {"img": {".png", ".jpg", ".webp"}, "vid": {".mp4", ".mov", ".webm"}}.get(ext)
    folder = "img" if ext in {".png", ".jpg", ".webp"} else ("vid" if ext in {".mp4", ".mov", ".webm"} else "file")
    dest_dir = ASSETS / "all" / group / folder
    dest_dir.mkdir(parents=True, exist_ok=True)
    name = rename or src.name
    dest = dest_dir / name
    shutil.copy2(src, dest)
    manifest.append((group, folder, "all/" + group + "/" + folder + "/" + name, dest.stat().st_size))


# Everything generated by our headless runs in the temp workspace.
for p in sorted((BASE / "rune-bench").iterdir()):
    if p.is_file():
        cp(p, "01_bench_runs")
for p in sorted((BASE / "rune-media").iterdir()):
    if p.is_file():
        cp(p, "02_media_wave1")
if (BASE / "rune-media2").exists():
    for p in sorted((BASE / "rune-media2").iterdir()):
        if p.is_file():
            cp(p, "03_media_wave2")
if (BASE / "rune-perf").exists():
    for p in sorted((BASE / "rune-perf").iterdir()):
        if p.is_file():
            cp(p, "04_perf")
for p in sorted((BASE / "rune-sheet").iterdir()):
    if p.is_file():
        cp(p, "05_video_frames")
for p in sorted(BASE.iterdir()):
    if not p.is_file():
        continue
    if p.suffix.lower() in {".png", ".mp4", ".mov", ".webm", ".json", ".jsonl", ".csv", ".log", ".py"} and p.name != "build_all_site.py":
        cp(p, "06_workspace")
for p in sorted((BASE / "rune-bench").glob("*.csv")):
    cp(p, "06_workspace")

# Artifacts written by Rune into the cloned repo root.
for p in sorted(REPO.iterdir()):
    if not p.is_file():
        continue
    if p.suffix.lower() in {".png", ".mp4", ".mov", ".webm", ".json"} or p.name == "--scene":
        cp(p, "07_repo_root", rename=("--scene.txt" if p.name == "--scene" else None))

# Raw wgpu scene stills.
for p in sorted((REPO / "target/site-scenes").glob("*.png")):
    cp(p, "08_site_scenes")

# Source code used for the integration.
for src, name in [
    (REPO / "crates/rune/examples/grain_compose.rs", "grain_compose.rs"),
    (REPO / "examples/hello/src/main.rs", "hello_main.rs"),
]:
    if src.exists():
        shutil.copy2(src, ASSETS / "src" / name)
        manifest.append(("09_source", "file", "src/" + name, src.stat().st_size))
for p in sorted(BASE.glob("*.py")):
    shutil.copy2(p, ASSETS / "scripts" / p.name)
    manifest.append(("09_source", "file", "scripts/" + p.name, p.stat().st_size))

# All official demo stills, kept in their folders.
for p in sorted((REPO / "demo").rglob("*.png")):
    rel = p.relative_to(REPO / "demo")
    dest = ASSETS / "all" / "10_demo" / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(p, dest)
    manifest.append(("10_demo", "img", "all/10_demo/" + rel.as_posix(), p.stat().st_size))
for p in sorted((REPO / "demo").rglob("*.mp4")):
    rel = p.relative_to(REPO / "demo")
    dest = ASSETS / "all" / "10_demo" / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(p, dest)
    manifest.append(("10_demo", "vid", "all/10_demo/" + rel.as_posix(), p.stat().st_size))

# Build the gallery, grouped.
groups = {}
for group, folder, rel, size in manifest:
    groups.setdefault(group, []).append((folder, rel, size))

LABELS = {
    "01_bench_runs": "01 - Headless app runs (stills, logs, trees, metrics)",
    "02_media_wave1": "02 - Media wave 1 (PNG, MP4, MOV, strips)",
    "03_media_wave2": "03 - Media wave 2 (advanced formats and scripts)",
    "04_perf": "04 - Perf profiles and microbenchmarks",
    "05_video_frames": "05 - Frames extracted from generated films",
    "06_workspace": "06 - Workspace outputs and harness data",
    "07_repo_root": "07 - Artifacts written into the Rune repo root",
    "08_site_scenes": "08 - Raw wgpu scenes at 1920x1080",
    "09_source": "09 - Source code and reproducible harnesses",
    "10_demo": "10 - Official Rune demo library",
}

parts = []
for group in sorted(groups):
    items = groups[group]
    parts.append('<details open><summary style="cursor:pointer;font:600 15px/1.4 inherit;margin:22px 0 12px">'
                 + html.escape(LABELS.get(group, group)) + ' <span style="color:var(--muted);font:11px ui-monospace,monospace">'
                 + str(len(items)) + ' files</span></summary><div class="grid">')
    for folder, rel, size in items:
        url = "assets/" + rel
        kb = size / 1024
        sz = (f"{kb/1024:.1f} MB" if kb >= 1024 else f"{kb:.0f} KB")
        if folder == "img":
            body = f'<img loading="lazy" src="{html.escape(url)}" alt="">'
        elif folder == "vid":
            body = f'<video controls preload="none" src="{html.escape(url)}"></video>'
        else:
            body = f'<div style="padding:18px 13px;min-height:70px;font:12px/1.5 ui-monospace,monospace;color:var(--muted);word-break:break-all"><a class="raw" href="{html.escape(url)}">{html.escape(Path(rel).name)}</a></div>'
        cap = f'<div class="cap"><b style="word-break:break-all">{html.escape(Path(rel).name)}</b><small>{sz} &middot; <a class="raw" href="{html.escape(url)}">open</a></small></div>'
        parts.append('<div class="card">' + body + cap + '</div>')
    parts.append('</div></details>')

gallery = ('<section><div class="sec-head"><span class="sec-num">10</span><h2>Everything generated</h2>'
           '<span class="sec-note">complete artifact index - every file on this sheet</span></div>'
           + "".join(parts) + '</section>')

index = SITE / "index.html"
text = index.read_text(encoding="utf-8")
if "Everything generated" in text:
    head, tail = text.split('<section><div class="sec-head"><span class="sec-num">10</span><h2>Everything generated</h2>', 1)
    _, footer = tail.split("<footer>", 1)
    text = head.rsplit("</footer>", 1)[0].rsplit("<footer>", 1)[0] + "</div>\n</body>\n</html>\n"
    # keep the curated final section (Download everything) intact
    text = head.rsplit("<footer>", 1)[0] + gallery + "<footer>" + footer
else:
    text = text.replace("<footer>", gallery + "<footer>")
index.write_text(text, encoding="utf-8")

total = sum(p.stat().st_size for p in ASSETS.rglob("*") if p.is_file())
count = len([p for p in ASSETS.rglob("*") if p.is_file()])
print("FILES", count, "TOTAL_MB", round(total / 1024 / 1024, 1))
print("GROUPS", {k: len(v) for k, v in sorted(groups.items())})
